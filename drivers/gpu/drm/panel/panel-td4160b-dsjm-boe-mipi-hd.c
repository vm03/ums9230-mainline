static int td4160b_backlight_update_status(struct backlight_device *bl)
{
	struct td4160b_panel *ctx = bl_get_data(bl);
	u16 brightness = backlight_get_brightness(bl);
	u8 payload[2] = { brightness >> 8, brightness & 0xff };
	int ret;

	/* The downstream OLED backlight writes DCS 0x51 with a 12-bit value. */
	if (!ctx->prepared)
		return 0;

	ret = mipi_dsi_dcs_write(ctx->dsi, MIPI_DCS_SET_DISPLAY_BRIGHTNESS,
				 payload, sizeof(payload));
	if (ret < 0) {
		dev_err(&ctx->dsi->dev, "failed to set OLED brightness %u: %d\n",
			brightness, ret);
		return ret;
	}

	dev_dbg(&ctx->dsi->dev, "OLED brightness set to %u/4095\n", brightness);
	return 0;
}

static const struct backlight_ops td4160b_backlight_ops = {
	.options = BL_CORE_SUSPENDRESUME,
	.update_status = td4160b_backlight_update_status,
};

static int td4160b_panel_off(struct td4160b_panel *ctx)
{
	return td4160b_panel_write_commands(ctx, td4160b_sleep_in_cmds,
					    ARRAY_SIZE(td4160b_sleep_in_cmds));
}

static int td4160b_panel_prepare(struct drm_panel *panel)
{
	struct td4160b_panel *ctx = to_td4160b_panel(panel);
	int ret;

	dev_info(&ctx->dsi->dev, "prepare: begin\n");
	ret = td4160b_panel_power_on(ctx);
	if (ret)
		return ret;
	td4160b_panel_reset(ctx);

	ret = td4160b_panel_on(ctx);
	if (ret < 0) {
		dev_err(&ctx->dsi->dev, "prepare: failed to initialize panel: %d\n", ret);
		td4160b_panel_power_off(ctx);
		td4160b_panel_reset_off(ctx);
		if (ctx->supply)
			regulator_disable(ctx->supply);
		return ret;
	}

	ctx->prepared = true;
	dev_info(&ctx->dsi->dev, "prepare: complete\n");
	return 0;
}

static int td4160b_panel_unprepare(struct drm_panel *panel)
{
	struct td4160b_panel *ctx = to_td4160b_panel(panel);
	int ret;

	dev_info(&ctx->dsi->dev, "unprepare: begin\n");
	ctx->prepared = false;
	ret = td4160b_panel_off(ctx);
	/* Match downstream order: AVEE off, AVDD off, reset low, regulator off. */
	td4160b_panel_power_off(ctx);
	td4160b_panel_reset_off(ctx);
	if (ctx->supply) {
		int power_ret = regulator_disable(ctx->supply);

		if (power_ret) {
			dev_err(&ctx->dsi->dev, "failed to disable panel supply: %d\n",
				power_ret);
			if (!ret)
				ret = power_ret;
		}
	}
	dev_info(&ctx->dsi->dev, "unprepare: complete (ret=%d)\n", ret);

	return ret;
}

