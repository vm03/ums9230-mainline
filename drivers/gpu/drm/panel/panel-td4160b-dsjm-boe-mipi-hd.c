/*
 * Mainline DRM panel driver derived from:
 *   lcd_td4160b_dsjm_boe_mipi_hd.dtsi
 *
 * TD4160B DSJM BOE, 720x1604, 4-lane MIPI DSI, RGB888.
 * The source DTS sets sprd,use-dcs-write, so initialization commands are
 * sent using DCS writes. Command payloads and delays are kept from the DTS.
 */

